export function getCountryNameJa(team: Team) {
  return (
    (team.tla ? countryNameJaByTla[team.tla.toUpperCase()] : undefined) ??
    countryNameJaByName[normalize(team.name)] ??
    countryNameJaByName[normalize(team.shortName)] ??
    team.shortName
  );
}

function normalize(value: string) {
  return value.toLowerCase().replace(/^the\s+/, "").trim();
}
